// Generates the voiceover, one wav per line, with Cartesia TTS, then transcribes each line with Cartesia
// STT for word times. Writes assets/vo/lines.js (globalThis.VO_LINES: text, duration, words), which the
// scenes and scripts/sfx.ts read, so actions land on the spoken word.
// Run: bun scripts/voice.ts [lineId...]   (needs CARTESIA_API_KEY; no args = all lines)
//      bun scripts/voice.ts --align        (only redo word times)

import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

const ROOT = path.join(import.meta.dirname, '..')
const OUT = path.join(ROOT, 'assets/vo')
const VOICE_ID = '2c1a6790-7bf0-4caf-af10-5a69b765e475' // Tommy's pick (earlier cuts: db6b0ed5 Skylar, 3a301a54)
const MODEL = 'sonic-3.5'

export const LINES: Record<string, string> = {
  l1: 'Your agent can use a browser on its own. It signs in, fills in forms, clicks through.',
  l2: 'Until it reaches a step only you can do. Like a code sent to your phone.',
  l3: 'The obvious fix is to pull that tab in front of you. But you were busy.',
  l4: 'So instead, Playwriter leaves your focus alone. It puts a small card next to the field, and waits.',
  l5: 'Then the agent sends you a link. It points to Playwriter, running on localhost, on your own machine.',
  l6: 'Click it, and the right tab comes to the front, scrolled to the exact spot that needs you.',
  l7: 'You type the code. The card says got it, and the agent carries on. Nothing to type in chat.',
  l8: "Rather not? Close the card, and the agent asks you in chat instead.",
  l9: "That's handoff, in the latest Playwriter.",
}

const HEADERS = { 'X-API-Key': process.env.CARTESIA_API_KEY ?? '', 'Cartesia-Version': '2025-04-16' }

async function tts({ text, file, signal }: { text: string; file: string; signal: AbortSignal }) {
  const res = await fetch('https://api.cartesia.ai/tts/bytes', {
    method: 'POST',
    signal,
    headers: { ...HEADERS, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model_id: MODEL,
      transcript: text,
      voice: { mode: 'id', id: VOICE_ID },
      language: 'en',
      output_format: { container: 'wav', encoding: 'pcm_s16le', sample_rate: 48000 },
    }),
  })
  if (!res.ok) throw new Error(`cartesia ${res.status}: ${await res.text()}`)
  fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()))
}

async function words({ file, signal }: { file: string; signal: AbortSignal }) {
  const form = new FormData()
  form.append('file', new Blob([fs.readFileSync(file)]), path.basename(file))
  form.append('model', 'ink-whisper')
  form.append('language', 'en')
  form.append('timestamp_granularities[]', 'word')
  const res = await fetch('https://api.cartesia.ai/stt', { method: 'POST', signal, headers: HEADERS, body: form })
  if (!res.ok) throw new Error(`cartesia stt ${res.status}: ${await res.text()}`)
  const json = (await res.json()) as { words: Array<{ word: string; start: number }> }
  return json.words.map((w) => ({ word: w.word.trim().toLowerCase().replace(/[^a-z0-9']/g, ''), start: w.start }))
}

function duration(file: string) {
  return Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file]).toString().trim())
}

fs.mkdirSync(OUT, { recursive: true })
const align = process.argv.includes('--align')
const only = process.argv.slice(2).filter((a) => !a.startsWith('--'))
for (const [id, text] of Object.entries(LINES)) {
  if (align || (only.length && !only.includes(id))) continue
  const raw = path.join(OUT, `${id}.raw.wav`)
  console.log(`[voice] ${id}: generating`)
  await tts({ text, file: raw, signal: AbortSignal.timeout(60_000) })
  // trim edge silence, clean chain, level to -16 LUFS (sound-effects skill)
  execFileSync('ffmpeg', [
    '-loglevel', 'error', '-y', '-i', raw,
    '-af', 'silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,highpass=f=80,acompressor=threshold=-20dB:ratio=3:attack=5:release=100:makeup=2,loudnorm=I=-16:TP=-1.5:LRA=7',
    '-ar', '48000', '-ac', '2', path.join(OUT, `${id}.wav`),
  ])
  fs.rmSync(raw)
  console.log(`[voice] ${id}: ${duration(path.join(OUT, `${id}.wav`)).toFixed(2)} s`)
}

const lines = []
for (const [id, text] of Object.entries(LINES)) {
  const file = path.join(OUT, `${id}.wav`)
  console.log(`[voice] ${id}: word times`)
  lines.push({ id, text, duration: Number(duration(file).toFixed(3)), words: await words({ file, signal: AbortSignal.timeout(60_000) }) })
}
fs.writeFileSync(path.join(OUT, 'lines.js'), `// generated by scripts/voice.ts\nglobalThis.VO_LINES = ${JSON.stringify(lines)}\n`)
console.log(`[voice] total ${lines.reduce((a, l) => a + l.duration, 0).toFixed(2)} s of speech`)
